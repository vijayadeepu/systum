import 'dart:convert';

import 'package:flutter/material.dart';

import '../../../core/theme/app_spacing.dart';
import '../../../shared/utils/id_generator.dart';
import '../models/task.dart';

/// A small, AI-friendly import contract. An AI can produce either a JSON array
/// or `{ "tasks": [...] }`; dates use ISO-8601 and priority is 1 (low), 2
/// (medium), or 3 (high).
class ImportedTasks {
  const ImportedTasks(this.tasks);

  final List<Task> tasks;
}

Future<ImportedTasks?> showImportTasksDialog(BuildContext context) {
  return showDialog<ImportedTasks>(
    context: context,
    builder: (_) => const _ImportTasksDialog(),
  );
}

class _ImportTasksDialog extends StatefulWidget {
  const _ImportTasksDialog();

  @override
  State<_ImportTasksDialog> createState() => _ImportTasksDialogState();
}

class _ImportTasksDialogState extends State<_ImportTasksDialog> {
  final _controller = TextEditingController();
  String? _error;

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  void _import() {
    try {
      final decoded = jsonDecode(_controller.text.trim());
      final rawTasks = decoded is List
          ? decoded
          : decoded is Map<String, dynamic>
          ? decoded['tasks']
          : null;
      if (rawTasks is! List || rawTasks.isEmpty) {
        throw const FormatException('Provide a non-empty tasks array.');
      }

      final now = DateTime.now().toUtc();
      final tasks = <Task>[];
      for (var index = 0; index < rawTasks.length; index++) {
        final raw = rawTasks[index];
        if (raw is! Map) throw FormatException('Task ${index + 1} is not an object.');
        final title = (raw['title'] ?? '').toString().trim();
        if (title.isEmpty || title.length > 120) {
          throw FormatException('Task ${index + 1} needs a title of 1–120 characters.');
        }
        final dueDate = _date(raw['dueDate']);
        final dueTime = _time(raw['dueTime']);
        if (dueTime != null && dueDate == null) {
          throw FormatException('Task ${index + 1}: dueTime requires dueDate.');
        }
        final priority = raw['priority'] == null
            ? 2
            : int.tryParse(raw['priority'].toString());
        if (priority == null || priority < 1 || priority > 3) {
          throw FormatException('Task ${index + 1}: priority must be 1, 2, or 3.');
        }
        tasks.add(
          Task(
            id: generateId(),
            title: title,
            description: _optionalText(raw['description']),
            category: _optionalText(raw['category']),
            dueDate: dueDate,
            dueTime: dueTime,
            dueTimezone: _optionalText(raw['dueTimezone']),
            priority: priority,
            createdAt: now,
            updatedAt: now,
          ),
        );
      }
      FocusScope.of(context).unfocus();
      Navigator.of(context).pop(ImportedTasks(tasks));
    } on FormatException catch (error) {
      setState(() => _error = error.message);
    } on Object {
      setState(() => _error = 'Invalid JSON.');
    }
  }

  DateTime? _date(Object? value) {
    if (value == null || value.toString().trim().isEmpty) return null;
    final parsed = DateTime.tryParse(value.toString());
    if (parsed == null) throw const FormatException('Dates must be ISO-8601, e.g. 2026-11-22.');
    return DateTime(parsed.year, parsed.month, parsed.day);
  }

  int? _time(Object? value) {
    if (value == null || value.toString().trim().isEmpty) return null;
    final match = RegExp(r'^(\d{1,2}):(\d{2})$').firstMatch(value.toString().trim());
    final hour = int.tryParse(match?.group(1) ?? '');
    final minute = int.tryParse(match?.group(2) ?? '');
    if (hour == null || minute == null || hour > 23 || minute > 59) {
      throw const FormatException('Times must use HH:MM, e.g. 09:30.');
    }
    return hour * 3600 + minute * 60;
  }

  String? _optionalText(Object? value) {
    final text = value?.toString().trim();
    return text == null || text.isEmpty ? null : text;
  }

  @override
  Widget build(BuildContext context) {
    return AlertDialog(
      title: const Text('Import tasks from AI'),
      content: SizedBox(
        width: 560,
        child: SingleChildScrollView(
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              const Text('Paste JSON generated by any AI. Dates use YYYY-MM-DD; times use HH:MM.'),
              const SizedBox(height: AppSpacing.sm),
              const SelectableText(
                '[{"title":"Call Alex","description":"Discuss launch","dueDate":"2026-11-24","dueTime":"09:30","priority":2}]',
                style: TextStyle(fontFamily: 'monospace', fontSize: 12),
              ),
              const SizedBox(height: AppSpacing.md),
              TextField(
                controller: _controller,
                minLines: 8,
                maxLines: 16,
                keyboardType: TextInputType.multiline,
                decoration: InputDecoration(
                  labelText: 'Task JSON',
                  hintText: '{"tasks": [...] }',
                  errorText: _error,
                  border: const OutlineInputBorder(),
                ),
                onChanged: (_) => setState(() => _error = null),
              ),
            ],
          ),
        ),
      ),
      actions: [
        TextButton(onPressed: () => Navigator.pop(context), child: const Text('Cancel')),
        FilledButton(onPressed: _import, child: const Text('Import tasks')),
      ],
    );
  }
}
